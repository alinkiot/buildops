def add_title_block(doc: Document) -> None:
    section = doc.sections[0]
    section.top_margin = Inches(1)
    section.bottom_margin = Inches(1)
    section.left_margin = Inches(1)
    section.right_margin = Inches(1)
    section.header_distance = Inches(0.492)
    section.footer_distance = Inches(0.492)

    hp = section.header.paragraphs[0]
    hp.text = ""
    hp.alignment = WD_ALIGN_PARAGRAPH.LEFT
    set_font(hp.add_run("详细需求设计说明书"), size=9, color=MUTED)

    fp = section.footer.paragraphs[0]
    fp.text = ""
    fp.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    set_font(fp.add_run("施工企业全流程运营托管数字化系统"), size=9, color=MUTED)

    para(doc, "", after=8)
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(4)
    set_font(p.add_run("详细需求设计说明书"), size=23, color=RGBColor(0, 0, 0), bold=True)
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(14)
    set_font(p.add_run("施工企业全流程运营托管数字化系统"), size=15, color=RGBColor(55, 55, 55))

    meta = [
        ("文档版本:", "V1.0"),
        ("依据文档:", "《施工企业全流程运营托管数字化系统_PRD》"),
        ("设计范围:", "业务需求分析、功能设计、数据字段、状态流转、规则预警、权限验收"),
        ("适用对象:", "产品、研发、测试、实施、托管运营团队"),
        ("生成日期:", date.today().isoformat()),
    ]
    for label, value in meta:
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(2)
        r = p.add_run(label + " ")
        set_font(r, size=11, color=INK, bold=True)
        set_font(p.add_run(value), size=11, color=INK)

    rule = doc.add_paragraph()
    p_pr = rule._p.get_or_add_pPr()
    pbdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "8")
    bottom.set(qn("w:space"), "1")
    bottom.set(qn("w:color"), "2E74B5")
    pbdr.append(bottom)
    p_pr.append(pbdr)


def setup_styles(doc: Document) -> None:
    normal = doc.styles["Normal"]
    normal.font.name = "Calibri"
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "Microsoft YaHei")
    normal.font.size = Pt(11)
    normal.paragraph_format.space_after = Pt(6)
    normal.paragraph_format.line_spacing = 1.1
    for style_name in ["List Bullet", "List Number"]:
        style = doc.styles[style_name]
        style.font.name = "Calibri"
        style._element.rPr.rFonts.set(qn("w:eastAsia"), "Microsoft YaHei")
        style.font.size = Pt(11)
        style.paragraph_format.space_after = Pt(5)
        style.paragraph_format.line_spacing = 1.15


def add_numbered(doc: Document, text: str) -> None:
    p = doc.add_paragraph(style="List Number")
    p.paragraph_format.space_after = Pt(4)
    set_font(p.add_run(text), size=10.5, color=INK)


def split_items(text: str) -> list[str]:
    return [x.strip() for x in text.split("、") if x.strip()]


def module_requirement_rows(module: dict, details: dict) -> list[tuple[str, str, str, str, str, str]]:
    rows = []
    scenes = ["新增/维护", "查询/筛选", "规则校验", "预警/待办", "导出/报表"]
    for index, feature in enumerate(module["features"], 1):
        scene = scenes[(index - 1) % len(scenes)]
        rows.append(
            (
                f"{module['id']}-DR-{index:02d}",
                scene,
                feature.split("：")[0],
                feature,
                "用户提交数据后，系统校验必填项、权限、状态和业务规则；通过后保存并写入日志，异常时返回原因。",
                "功能可完成端到端操作；关键字段可查；异常有提示；结果可追溯到操作人和时间。",
            )
        )
    rows.append(
        (
            f"{module['id']}-DR-99",
            "模块联动",
            "跨模块数据同步",
            f"与项目中心、文件中心、预警中心、审计日志联动；核心对象包括：{module['objects']}。",
            "系统按项目、企业、角色、密级过滤数据，并将风险事件推送至责任人。",
            "跨模块字段口径一致；预警可闭环；日志可检索。",
        )
    )
    return rows


def add_module_section(doc: Document, module: dict, index: int) -> None:
    details = module_details[module["id"]]
    heading(doc, f"5.{index} {module['name']}（{module['id']}）", 2)
    para(doc, f"模块定位：{module['position']}。")
    para(doc, f"需求分析：{module['pain']}本模块需要把线下台账、文件、审批和预警规则产品化，形成可配置、可追溯、可交付的业务闭环。")

    add_table(
        doc,
        ["设计项", "详细说明"],
        [
            ("主要页面", details["pages"]),
            ("核心流程", details["workflow"]),
            ("关键字段", details["fields"]),
            ("状态流转", details["statuses"]),
            ("业务规则", details["rules"]),
            ("异常处理", details["exceptions"]),
        ],
        [1600, 7760],
        font_size=9,
    )

    heading(doc, f"5.{index}.1 功能点详细设计", 3)
    add_table(
        doc,
        ["编号", "场景", "功能点", "需求描述", "系统处理", "验收标准"],
        module_requirement_rows(module, details),
        [1050, 1050, 1450, 2600, 2050, 1160],
        font_size=7.7,
    )

    heading(doc, f"5.{index}.2 字段与权限补充", 3)
    field_rows = []
    for no, field in enumerate(split_items(details["fields"]), 1):
        required = "是" if no <= 5 else "按场景"
